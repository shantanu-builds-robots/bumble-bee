#!/usr/bin/env python3
"""Plan a course's delivery mission around its buildings and write it for bumble-bee's deliver node.

    python3 path_planning/plan_mission.py delivery_city      # -> path_planning/missions/delivery_city.yaml and .png

The YAML lists, per delivery, the waypoints to the pickup and from there to the drop, then the way
home. Each list ends at its target and leaves out the point it starts from. Every leg also carries a
minimum-snap trajectory through the same route (trajectory.py). Fly it in Gazebo with:
    ros2 run drone_delivery deliver --ros-args -p mission:=<path>/missions/delivery_city.yaml \
        -p route_mode:=trajectory        # or waypoints (the default): steer at each corner in turn
"""

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

import course, planner, trajectory

ROOT = Path(__file__).resolve().parent
PX = 60          # pixels per metre in the picture


def fmt(p) -> str:
    return f"[{p[0]:.3f}, {p[1]:.3f}]"


def traj_yaml(tr: trajectory.Trajectory, indent: str) -> list[str]:
    row = lambda c: "[" + ", ".join(f"{v:.6g}" for v in c) + "]"  # noqa: E731
    return [f"{indent}durations: {row(tr.durations)}",
            f"{indent}x: [{', '.join(row(c) for c in tr.coeffs[0])}]",
            f"{indent}y: [{', '.join(row(c) for c in tr.coeffs[1])}]"]


def write_yaml(c: course.Course, legs: list[dict], path: Path):
    m = c.mission
    peaks = np.array([leg["trajectory"].peaks() for leg in legs]).max(axis=0)
    lines = [f"# Generated by path_planning/plan_mission.py from path_planning/courses/{c.name}.yaml. Do not edit.",
             f"# Trajectories: minimum snap, 7th-order segments in normalised time s in [0, 1];"
             f" peak {peaks[0]:.2f} m/s and {peaks[1]:.2f} m/s^2.",
             f"# Waypoints keep {planner.DRONE_RADIUS + planner.MARGIN:.2f} m (drone radius {planner.DRONE_RADIUS} m"
             f" + margin {planner.MARGIN} m) from every building at cruise height.",
             f"course: {c.name}", f"cruise: {m.cruise}", f"home: {fmt(m.home)}", "deliveries:"]
    for k, (pick, drop) in enumerate(m.deliveries):
        to_pick, to_drop = legs[2 * k]["waypoints"][1:], legs[2 * k + 1]["waypoints"][1:]
        lines += [f"  - pickup: {fmt(pick)}", f"    drop: {fmt(drop)}",
                  f"    to_pickup: [{', '.join(fmt(p) for p in to_pick)}]",
                  f"    to_drop: [{', '.join(fmt(p) for p in to_drop)}]"]
        lines += ["    traj_to_pickup:"] + traj_yaml(legs[2 * k]["trajectory"], "      ")
        lines += ["    traj_to_drop:"] + traj_yaml(legs[2 * k + 1]["trajectory"], "      ")
    lines.append(f"to_home: [{', '.join(fmt(p) for p in legs[-1]['waypoints'][1:])}]")
    lines += ["traj_to_home:"] + traj_yaml(legs[-1]["trajectory"], "  ")
    path.write_text("\n".join(lines) + "\n")


def draw(c: course.Course, legs: list[dict], path: Path):
    obstacles = planner.Obstacles.from_course(c, c.mission.cruise)
    pts = np.vstack([c.mission.home] + [p for d in c.mission.deliveries for p in d] + list(obstacles.centres))
    lo, hi = pts.min(axis=0) - 1.5, pts.max(axis=0) + 1.5
    w, h = ((hi - lo) * PX).astype(int)
    img = Image.new("RGB", (w, h), (236, 238, 232))
    d = ImageDraw.Draw(img)
    to_px = lambda p: ((p[0] - lo[0]) * PX, (hi[1] - p[1]) * PX)  # noqa: E731  (y up)

    def rect(centre, half, yaw, grow=0.0):
        cs, sn = np.cos(yaw), np.sin(yaw)
        corners = [centre + np.array([cs * x - sn * y, sn * x + cs * y])
                   for x, y in [(-1, -1), (1, -1), (1, 1), (-1, 1)] for x, y in [((half[0] + grow) * x, (half[1] + grow) * y)]]
        return [to_px(p) for p in corners]

    clearance = planner.DRONE_RADIUS + planner.MARGIN
    for cen, half, yaw in zip(obstacles.centres, obstacles.halves, obstacles.yaws):
        d.polygon(rect(cen, half, yaw, clearance), outline=(200, 160, 150))
    for cen, half, yaw in zip(obstacles.centres, obstacles.halves, obstacles.yaws):
        d.polygon(rect(cen, half, yaw), fill=(92, 96, 104))
    for p in c.pads:
        d.rectangle([to_px(p[:2] + [-0.5, 0.5]), to_px(p[:2] + [0.5, -0.5])], fill=(60, 140, 215))
    for leg in legs:  # straight line (what the old mission flew), then the planned path
        a, b = leg["waypoints"][0], leg["waypoints"][-1]
        if leg["straight_clearance"] < clearance:
            n = int(np.linalg.norm(b - a) / 0.15)
            for i in range(0, n, 2):
                d.line([to_px(a + (b - a) * i / n), to_px(a + (b - a) * (i + 1) / n)], fill=(210, 60, 50), width=3)
    for leg in legs:
        d.line([to_px(p) for p in leg["waypoints"]], fill=(242, 183, 5), width=5)
        for p in leg["waypoints"][1:-1]:
            x, y = to_px(p)
            d.ellipse([x - 5, y - 5, x + 5, y + 5], fill=(12, 26, 14))
    for _, p in [(None, c.mission.home)] + [(None, q) for dl in c.mission.deliveries for q in dl]:
        x, y = to_px(p)
        d.ellipse([x - 7, y - 7, x + 7, y + 7], outline=(12, 26, 14), width=3)
    d.text((10, 10), f"{c.name}: planned (yellow) vs straight line through a building (red dashes)",
           fill=(12, 26, 14))
    img.save(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("course")
    ap.add_argument("-o", "--out", type=Path, default=ROOT / "missions")
    ap.add_argument("--v-max", type=float, default=trajectory.V_MAX, help="trajectory speed limit [m/s]")
    ap.add_argument("--a-max", type=float, default=trajectory.A_MAX, help="trajectory acceleration limit [m/s^2]")
    args = ap.parse_args()
    c = course.load(args.course)
    legs = planner.plan_mission(c)
    obstacles = planner.Obstacles.from_course(c, c.mission.cruise)
    for leg in legs:
        leg["trajectory"] = trajectory.fit(leg["waypoints"], obstacles, planner.DRONE_RADIUS + trajectory.CURVE_MARGIN,
                                           args.v_max, args.a_max)
    args.out.mkdir(parents=True, exist_ok=True)
    write_yaml(c, legs, args.out / f"{c.name}.yaml")
    draw(c, legs, args.out / f"{c.name}.png")
    blocked = sum(L["straight_clearance"] < planner.DRONE_RADIUS + planner.MARGIN for L in legs)
    print(f"{c.name}: {len(legs)} legs, {blocked} rerouted around buildings, "
          f"min clearance {min(L['clearance'] for L in legs):.2f} m, "
          f"{sum(L['length'] for L in legs):.1f} m flown vs {sum(L['straight_length'] for L in legs):.1f} m straight")
    print(f"trajectories: {sum(L['trajectory'].total for L in legs):.1f} s in transit at up to {args.v_max} m/s, "
          f"min clearance {min(L['trajectory'].clearance(obstacles).min() for L in legs):.2f} m")
    print(args.out / f"{c.name}.yaml")


if __name__ == "__main__":
    main()
